// 家財名の表記ゆれを吸収して見出し語にする（全サイト共通）。
//
// 各サイトが同じ物を違う言い方で送ってくる。
//   引越し侍・ズバット … 「タンス（大）」「ベッド（シングル）」「テレビ（40インチ以上）」
//   価格.com          … 「タンス大」  「シングルベッド」  「テレビ（４０インチ以上）」（全角）
// ここで揃えないと、同じ物が別物として扱われる。
//
// ※以前は Estimate.jsx（見積書への割り当て）と LeadDetailModal.jsx（画面の分類）で
//   別々のルールを持っていた。片方だけ直す事故になるので1か所にまとめる。
//
// 例：ソファー（2人掛け）→ ソファ（2人掛け） ／ タンス類（大）→ タンス（大）
export const canonKazai = (s) => String(s || '').normalize('NFKC').replace(/[\s　]/g, '')
  .replace(/\(/g, '（').replace(/\)/g, '）')
  .replace(/ー(?=（|$)/g, '')
  .replace(/類(?=（|$)/g, '')
